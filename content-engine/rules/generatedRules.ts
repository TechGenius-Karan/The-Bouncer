// --- sound rules -------------------------------------------------------------
//
// A third axis. Every other rule in the taxonomy asks about spelling or about
// meaning; these ask what the word sounds like, which a player has to reach for
// differently — often by saying the word under their breath.
//
// All of them read `word.phonetics`, precomputed from CMUdict into
// words/phonetics.ts. It is null for the ~2% of the bank with no pronunciation,
// and every rule below treats that as OUT. Never as a match: a word the game
// cannot pronounce silently becoming an IN answer is a wrong answer the player
// has no way to reason about.

/** "Three syllables when you say it out loud." */
export function syllableCountRule(count: number): Rule {
  return {
    id: `syllables-${count}`,
    name: `${count} Syllable${count === 1 ? '' : 's'}`,
    templateId: 'syllable-count',
    descriptionTemplate: `The word has exactly ${count} syllable${count === 1 ? '' : 's'} when spoken.`,
    family: 'lexical-structural',
    mechanic: 'sound',
    subtlety: 3,
    // Counting, like word-length — but counting something you can only get at
    // by pronouncing the word, which is a different act from counting letters.
    aha: 3,
    evaluate: (word) => word.phonetics?.syllables === count,
  }
}

/**
 * "Longer written than spoken." The player has to notice the gap between how a
 * word looks and how it sounds.
 *
 * Named for what it actually measures. The count is letters minus phonemes, so
 * digraphs land in it too — "cheese" scores 3 without having three silent
 * letters in the way anyone means that phrase. Calling it "Silent Letters"
 * would promise something the evaluator doesn't deliver, and the reveal text is
 * the one thing a player checks their reasoning against.
 */
export function silentLettersRule(minSilent: number): Rule {
  return {
    id: `silent-letters-${minSilent}`,
    name: 'More Letters Than Sounds',
    templateId: 'silent-letters',
    descriptionTemplate: `The word has at least ${minSilent} more letters than it has sounds.`,
    family: 'lexical-structural',
    mechanic: 'sound',
    subtlety: 3,
    aha: 4,
    evaluate: (word) => (word.phonetics?.silent ?? 0) >= minSilent,
  }
}

/** "Sounds exactly like another word" — great/grate, throne/thrown, pear/pair. */
export function homophoneRule(): Rule {
  return {
    id: 'has-homophone',
    name: 'Sounds Like Another Word',
    templateId: 'homophone',
    descriptionTemplate: 'The word sounds exactly like a different word.',
    family: 'lexical-structural',
    mechanic: 'sound',
    subtlety: 3,
    aha: 4,
    evaluate: (word) => word.phonetics?.homophone === true,
  }
}

/**
 * "They all start with a K sound" — coffee, kitten, quiet, chemistry.
 *
 * The sharpest thing the sound family can do, and the one rule here that no
 * spelling rule could imitate: the words share a sound and share no letter. Only
 * phonemes spelled several ways in the bank get a rule at all
 * (MIN_MINORITY_SPELLING_SHARE), because "starts with a B sound" is just "starts
 * with B" with extra steps.
 *
 * `variantOf` returns the first *letter*, which matters more here than anywhere
 * else in the taxonomy: it makes draftClueSet span at least two spellings, so the
 * clue set is coffee/kitten/quiet rather than three c-words that teach the player
 * the wrong rule.
 */
export function initialSoundRule(phoneme: string): Rule {
  const label = SOUND_LABEL[phoneme] ?? phoneme
  return {
    id: `initial-sound-${phoneme.toLowerCase()}`,
    name: `Starts With a "${label}" Sound`,
    templateId: 'initial-sound',
    descriptionTemplate: `The word starts with a "${label}" sound, however it is spelled.`,
    family: 'lexical-structural',
    mechanic: 'sound',
    subtlety: 3,
    aha: 5,
    evaluate: (word) => word.phonetics?.first === phoneme,
    variantOf: (word) => (word.phonetics?.first === phoneme ? word.spelling[0] : null),
  }
}

/**
 * "The first letter makes no sound at all" — knee, gnome, wrist, write, hour.
 *
 * 91 words, from a closed list of silent initial digraphs plus silent H; see
 * SILENT_INITIALS in scripts/buildPhonetics.ts for why that list is hardcoded
 * rather than inferred.
 *
 * `variantOf` is the silent letter. Without it the first real batch drew
 * `wrestling, knowing, wrong` — a clue set whose shared -ng ending generated
 * three spurious decoys ("Ends With NG", "Contains G") and taught the player to
 * look at the end of the word rather than the start. Spanning variants gives
 * knee / wrist / honest instead.
 */
export function silentFirstLetterRule(): Rule {
  return {
    id: 'silent-first-letter',
    name: 'Silent First Letter',
    templateId: 'silent-first-letter',
    descriptionTemplate: 'The word begins with a letter you do not pronounce.',
    family: 'lexical-structural',
    mechanic: 'sound',
    subtlety: 3,
    aha: 5,
    evaluate: (word) => word.phonetics?.silentFirst === true,
    variantOf: (word) => (word.phonetics?.silentFirst ? word.spelling[0] : null),
  }
}

/**
 * "A long word you say in one beat" — cheese, mosque, square, spring, wrench.
 *
 * Spelling against sound again, from the other direction: the word looks like it
 * should take a while and doesn't. `minLength` is 6 rather than swept, because
 * the three candidate lengths are the same idea at three strengths and only one
 * should ship; soundRules.test.ts asserts the coverage floor so a bank change
 * that starved it would fail loudly.
 */
export function longOneSyllableRule(minLength: number): Rule {
  return {
    id: `one-syllable-long-${minLength}`,
    name: 'Long, But One Syllable',
    templateId: 'one-syllable-long',
    descriptionTemplate: `The word is ${minLength} letters or more, but only one syllable when spoken.`,
    family: 'lexical-structural',
    mechanic: 'sound',
    subtlety: 3,
    aha: 5,
    evaluate: (word) => word.phonetics?.syllables === 1 && word.length >= minLength,
  }
}

/**
 * "They all rhyme." The rhyme key is the last stressed vowel sound onward, so
 * it groups by how words END in speech rather than in spelling — "eight"
 * rhymes with "late" here, which no ends-with rule can express.
 *
 * `anchor` is a common bank word carrying the same key, and it exists purely so
 * the reveal names something. All 73 rhyme rules used to end with the identical
 * sentence, "The words all rhyme with each other" — 73 rules that read as one
 * puzzle played 73 ways, which is more repetitive than the hidden-word family
 * it was quietly out-drawing. "They all rhyme with RAIN" tells the player what
 * they were listening for.
 */
export function rhymeRule([key, anchor]: readonly [string, string]): Rule {
  return {
    id: `rhyme-${key.toLowerCase()}`,
    name: `Rhymes With "${anchor.toUpperCase()}"`,
    templateId: 'rhyme',
    descriptionTemplate: `The words all rhyme with "${anchor}".`,
    family: 'lexical-structural',
    mechanic: 'sound',
    subtlety: 3,
    // Demoted from 3 to filler. 73 rules all asking the same question is the
    // largest single template in the taxonomy, and even after mechanic and
    // template damping it still took 13% of every lexical draw — more than any
    // rule family that asks something a player hasn't already been asked this
    // week. At 2 it falls under FILLER_AHA_THRESHOLD, so MAX_FILLER_PER_WEEK
    // caps how many can reach the calendar at all, and it stops out-producing
    // the sound rules that are actually distinctive.
    aha: 2,
    evaluate: (word) => word.phonetics?.rhyme === key,
  }
}
