// Rules built from a parameter list rather than hand-written one at a time.
// This is what takes the taxonomy from ~19 usable rules (a repeat every two
// weeks on the medium tier) to a few hundred.
//
// The parameters live in ruleParams.ts, which is GENERATED by
// `npm run content:build-rule-params` after counting real coverage against the
// word bank. That indirection matters: the old hand-maintained letter list
// excluded j/x/z based on counts taken against a 417-word bank and nobody
// re-ran them after it grew to 5,000 (the real numbers were j:96, x:78, z:41),
// so three rules sat unusable for months. Regenerating the params after a
// word-bank change now unlocks newly-viable rules automatically.

/**
 * ARPAbet symbols a player would not recognise, in the reveal's own vocabulary.
 * Only the phonemes that can survive buildRuleParams' spelling-variety gate need
 * an entry; anything else falls through to the symbol itself.
 */
const SOUND_LABEL: Record<string, string> = { JH: 'J', ZH: 'ZH', HH: 'H' }

function article(word: string): string {
  return /^[aeiou]/.test(word) ? 'an' : 'a'
}

/** "The word hides ANIMAL inside it" — one rule per target. */
export function hiddenWordRule(target: string): Rule {
  return {
    id: `hidden-word-${target}`,
    name: `Hidden "${target}"`,
    templateId: 'hidden-word',
    descriptionTemplate: `The word hides "${target}" inside it.`,
    family: 'lexical-structural',
    mechanic: 'word-inside',
    // Was 4, which made every hidden-word rule spicy-only — one day a week.
    // It is the best-performing template in the whole taxonomy: 25% of its
    // puzzles get rejected, against 80% for ends-with and 88% for starts-with.
    // Locking the good material to Saturdays while filler carried the weekdays
    // was backwards. 3 keeps it spicy-eligible and adds it to medium.
    subtlety: 3,
    aha: 4,
    evaluate: (word) => word.features.hiddenWordHits.includes(target),
  }
}

/**
 * "The word hides a body part inside it" — the group version, which is a
 * better puzzle than any single target: the player gets a category insight
 * rather than spotting one fixed string.
 */
export function hiddenGroupRule(group: keyof typeof HIDDEN_WORD_GROUPS): Rule {
  const members = new Set<string>(HIDDEN_WORD_GROUPS[group])
  return {
    id: `hidden-group-${group.replace(/\s+/g, '-')}`,
    name: `Hides ${article(group)} ${group}`,
    templateId: 'hidden-group',
    descriptionTemplate: `The word hides the name of ${article(group)} ${group} inside it.`,
    family: 'lexical-structural',
    mechanic: 'word-inside',
    // Was 5, which made the highest-rated template in the taxonomy spicy-only —
    // one day a week for the puzzles most worth playing. The same mistake
    // hidden-word was in before the audit, and less defensible here: spotting
    // *some* animal is easier than spotting one specific target, so the group
    // version was rated harder than the individual version it generalises.
    // 3 keeps it spicy-eligible and adds it to medium.
    subtlety: 3,
    aha: 5,
    evaluate: (word) => word.features.hiddenWordHits.some((hit) => members.has(hit)),
    variantOf: (word) => word.features.hiddenWordHits.find((hit) => members.has(hit)) ?? null,
  }
}

export function startsWithRule(prefix: string): Rule {
  return {
    id: `starts-with-${prefix}`,
    name: `Starts With "${prefix.toUpperCase()}"`,
    templateId: 'starts-with',
    descriptionTemplate: `The word starts with "${prefix.toUpperCase()}".`,
    family: 'lexical-structural',
    mechanic: 'letter-pattern',
    subtlety: prefix.length > 1 ? 3 : 2,
    // 88% of starts-with puzzles have been rejected — the worst rate of any
    // template. aha is a selection weight (pickTrueRule uses aha / (1 +
    // rejectCount)), so rating it as filler is what stops it filling the
    // review queue with puzzles nobody wants.
    aha: 1,
    evaluate: (word) => word.spelling.startsWith(prefix),
  }
}

